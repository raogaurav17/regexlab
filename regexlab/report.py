def _trace_html(model, s: str) -> str:
    r = run_all(model, s)
    f = lambda items, p: "{" + ", ".join(f"{p}{i}" for i in items) + "}" if items else "∅"
    rows = []
    for i in range(len(s) + 1):
        rows.append(f"<tr><td>{i}</td><td>{escape(s[i - 1]) if i else '—'}</td>"
                    f"<td>{f(r['steps']['nfa'][i], 'q')}</td><td>{f(r['steps']['dfa'][i], 'D')}</td>"
                    f"<td>{f(r['steps']['min'][i], 'M')}</td></tr>")
    verdict = '<span class="ok">ACCEPTED</span>' if r["accepted"] else '<span class="bad">REJECTED</span>'
    note = "" if r["oracle"] is None else (" · matches Python <code>re</code>" if r["oracle"] == r["accepted"] else " · DIFFERS from Python re")
    return (f"<h3>Trace for <code>{escape(s) or '(empty)'}</code> — {verdict}{note}</h3>"
            "<div class='tablewrap'><table><thead><tr><th>Step</th><th>Read</th><th>NFA</th><th>DFA</th><th>Min DFA</th></tr></thead>"
            f"<tbody>{''.join(rows)}</tbody></table></div>")


def build_report(model, tests=()) -> str:
    c = {"ast": ast_size(model.ast), "nfa": model.nfa.n, "dfa": model.dfa.n, "min": model.min.n}
    toks = "".join(f'<span class="tok">{t.type} {escape(repr(t.value))}</span>' for t in model.tokens)
    graph = lambda key, title, cap: (f'<section class="card"><h2>{title}</h2><p class="cap">{cap}</p><div class="graph">'
                                     f'{draw_svg(getattr(model, key), key, LABELS[key])}</div></section>')
    traces = "".join(_trace_html(model, s) for s in tests)
    return f"""<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1">
<title>regexlab report - {escape(model.src)}</title><style>{_CSS}</style></head><body><main>
<h1>Regex → Automata report</h1><p class="sub">Generated by regexlab</p>
<section class="card"><h2>Regular expression</h2><div class="re"><code>{escape(model.src)}</code></div>
<h3>1 · Tokens (lexer)</h3><div>{toks}</div><h3>2 · Syntax tree (parser, {c['ast']} nodes)</h3><pre>{escape(chr(10).join(ast_lines(model.ast)))}</pre></section>
{graph('nfa', f"3 · ε-NFA — {c['nfa']} states", "Thompson's construction.")}
{graph('dfa', f"4 · DFA — {c['dfa']} states", "Subset construction; each state is a set of NFA states.")}
{graph('min', f"5 · Minimal DFA — {c['min']} states", "Hopcroft partition refinement; the dead state is omitted.")}
<section class="card"><h2>Tables</h2>{tables_html(model)}</section>
{f'<section class="card"><h2>Test strings</h2>{traces}</section>' if traces else ''}
</main></body></html>"""
